async (page) => {
  if(!page.url().startsWith('http://127.0.0.1:5371/'))throw new Error('Isolated catalog fixture required');
  await page.evaluate(()=>localStorage.removeItem('gingtto-cart'));
  const check=(ok,message)=>{if(!ok)throw new Error(message)};
  const styles=()=>page.locator('.style-group');
  const ready=()=>styles().first().waitFor();
  const noOverflow=()=>page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1);
  const columns=()=>page.locator('.style-colors').first().evaluate(el=>getComputedStyle(el).gridTemplateColumns.split(' ').length);
  const requests=[];page.on('request',r=>requests.push(r.url()));
  await page.setViewportSize({width:1600,height:1000});
  await page.goto('http://127.0.0.1:5371/shop');await ready();
  check(await styles().count()===12,'Default page is not twelve whole styles');
  check(await styles().first().locator('.color-card').count()===2,'Style colors are incomplete');
  check((await styles().first().innerText()).includes('CAT-13'),'Newest style not first');
  check((await styles().first().innerText()).includes('$10.00–$12.00'),'Price range missing');
  check(await columns()===4,'Desktop grid is not four columns');
  check(await page.locator('.color-image img').first().evaluate(el=>getComputedStyle(el).objectFit==='contain'),'Images cropped');
  await page.screenshot({path:'output/playwright/catalog-desktop.png',fullPage:false});
  const search=page.getByRole('searchbox',{name:'Search catalog'});
  await search.fill('CAT-13-Black');await page.locator('.catalog-filters').getByRole('button',{name:'Search',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.style-group').length===1);
  check(await styles().first().locator('.color-card').count()===2,'Color search discarded sibling colors');
  await page.getByRole('checkbox',{name:'In stock only'}).check();
  await page.locator('.catalog-filters').getByRole('button',{name:'Search',exact:true}).click();
  await ready();check(await styles().first().locator('.color-card').count()===2,'Stock filter split colors');
  await page.setViewportSize({width:900,height:1000});check(await columns()===3,'Tablet grid is not three columns');
  await page.setViewportSize({width:390,height:844});check(await columns()===2,'Mobile grid is not two columns');
  check(await noOverflow(),'Mobile catalog has horizontal overflow');
  await page.screenshot({path:'output/playwright/catalog-mobile.png',fullPage:true});
  await page.setViewportSize({width:1600,height:1000});
  await page.locator('.catalog-filters').getByRole('button',{name:'Reset',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.style-group').length===12);
  await page.getByRole('button',{name:'Next',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.style-group').length===3);
  check(await styles().last().locator('.color-card').count()===3,'Second page split the three-color style');
  await page.getByRole('link',{name:'PRE-SALE',exact:true}).first().click();await ready();
  check(await styles().count()===3,'Saved presale styles missing');
  check((await styles().first().innerText()).includes('CAT-12'),'Manual presale order not applied');
  await page.getByRole('link',{name:'GINGTTO',exact:true}).first().click();await ready();
  check(new URL(page.url()).pathname==='/shop','Brand logo does not open the catalog');
  await page.goto('http://127.0.0.1:5371/product/cat-13-white');
  await page.getByRole('spinbutton',{name:'Quantity 28/S',exact:true}).waitFor();
  check(await page.getByRole('button',{name:/^Color /}).count()===2,'Detail colors disagree with catalog identity');
  await page.getByRole('spinbutton',{name:'Quantity 28/S',exact:true}).fill('2');
  await page.getByRole('spinbutton',{name:'Quantity Tall XL',exact:true}).fill('1');
  await page.getByRole('button',{name:'ADD TO CART',exact:true}).click();
  const cart=await page.evaluate(()=>JSON.parse(localStorage.getItem('gingtto-cart')));
  check(cart.length===2 && cart.reduce((sum,r)=>sum+r.quantity,0)===3,'Multi-size cart failed');
  check(!requests.some(url=>new URL(url).pathname==='/api/home'),'Category menu still depends on retired home API');
  return {checks:18,wholeStyle:true,desktopTabletMobile:true,uncroppedImages:true,manualPresale:true,multiSizeCart:true,noLegacyHomeDependency:true};
}
